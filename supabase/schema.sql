-- ============================================================================
-- DevPath schema for Supabase (Postgres).
--
-- Two groups of tables:
--   1. Content: shared learning material, read-only from the app. Seeded by
--      seed.sql. Anyone (anon or signed in) can SELECT, nobody can write.
--   2. User data: progress, notes and preferences. Every row has a user_id that
--      references auth.users. RLS lets a signed-in user see and change only
--      their own rows.
--
-- Bilingual text uses *_en / *_ar columns on the same row, as in the .NET app.
-- Enum values are stored as text with CHECK constraints.
-- Run this file once in the Supabase SQL editor, before seed.sql.
-- ============================================================================

-- ---------- Content ----------

create table if not exists public.phases (
  id              integer generated by default as identity primary key,
  slug            text not null unique,
  sort_order      integer not null,
  title_en        text not null,
  title_ar        text not null,
  description_en  text not null default '',
  description_ar  text not null default ''
);

create table if not exists public.topics (
  id                integer generated by default as identity primary key,
  slug              text not null unique,
  phase_id          integer not null references public.phases (id) on delete restrict,
  sort_order        integer not null,
  skill             text not null check (skill in ('CSharp','AspNetCore','EfCore','SqlServer','TypeScript','Angular','FullStack','Testing','Git','Professional')),
  priority          text not null check (priority in ('Core','Important','Optional')),
  estimated_minutes integer not null,
  title_en          text not null,
  title_ar          text not null,
  summary_en        text not null default '',
  summary_ar        text not null default '',
  why_en            text not null default '',
  why_ar            text not null default '',
  how_en            text not null default '',
  how_ar            text not null default '',
  example_en        text not null default '',
  example_ar        text not null default '',
  code_sample       text,
  code_language     text,
  practice_task_en  text not null default '',
  practice_task_ar  text not null default '',
  challenge_en      text not null default '',
  challenge_ar      text not null default ''
);
create index if not exists topics_phase_order_idx on public.topics (phase_id, sort_order);

create table if not exists public.topic_prerequisites (
  topic_id              integer not null references public.topics (id) on delete cascade,
  prerequisite_topic_id integer not null references public.topics (id) on delete restrict,
  primary key (topic_id, prerequisite_topic_id),
  constraint topic_prerequisites_not_self check (topic_id <> prerequisite_topic_id)
);

create table if not exists public.resources (
  id                  integer generated by default as identity primary key,
  key                 text not null unique,
  title_en            text not null,
  title_ar            text,
  url                 text not null unique,
  source_name         text not null,
  type                text not null check (type in ('Documentation','Tutorial','Course','Video','Article','Reference','Tool')),
  difficulty          text not null check (difficulty in ('Beginner','Intermediate','Advanced')),
  is_free             boolean not null default true,
  verification_status text not null default 'Unverified' check (verification_status in ('Unverified','Verified','Broken')),
  last_verified_at    timestamptz,
  last_status_code    integer
);

create table if not exists public.resource_topics (
  resource_id integer not null references public.resources (id) on delete cascade,
  topic_id    integer not null references public.topics (id) on delete cascade,
  primary key (resource_id, topic_id)
);
create index if not exists resource_topics_topic_idx on public.resource_topics (topic_id);

create table if not exists public.projects (
  id                    integer generated by default as identity primary key,
  slug                  text not null unique,
  sort_order            integer not null,
  title_en              text not null,
  title_ar              text not null,
  summary_en            text not null default '',
  summary_ar            text not null default '',
  requirements_en       text not null default '',
  requirements_ar       text not null default '',
  tech_stack            text not null,
  start_after_phase_id  integer not null references public.phases (id) on delete restrict
);

create table if not exists public.project_milestones (
  id              integer generated by default as identity primary key,
  key             text not null unique,
  project_id      integer not null references public.projects (id) on delete restrict,
  sort_order      integer not null,
  title_en        text not null,
  title_ar        text not null,
  description_en  text not null default '',
  description_ar  text not null default ''
);
create index if not exists project_milestones_project_idx on public.project_milestones (project_id, sort_order);

create table if not exists public.project_tasks (
  id                      integer generated by default as identity primary key,
  key                     text not null unique,
  milestone_id            integer not null references public.project_milestones (id) on delete restrict,
  sort_order              integer not null,
  title_en                text not null,
  title_ar                text not null,
  description_en          text not null default '',
  description_ar          text not null default '',
  acceptance_criteria_en  text not null default '',
  acceptance_criteria_ar  text not null default '',
  estimated_minutes       integer not null,
  priority                text not null check (priority in ('High','Medium','Low')),
  is_change_request       boolean not null default false,
  unlock_at_percent       integer not null default 0 check (unlock_at_percent between 0 and 100)
);
create index if not exists project_tasks_milestone_idx on public.project_tasks (milestone_id, sort_order);

create table if not exists public.project_task_topics (
  project_task_id integer not null references public.project_tasks (id) on delete cascade,
  topic_id        integer not null references public.topics (id) on delete cascade,
  primary key (project_task_id, topic_id)
);
create index if not exists project_task_topics_topic_idx on public.project_task_topics (topic_id);

create table if not exists public.portfolio_checklist_items (
  id              integer generated by default as identity primary key,
  key             text not null unique,
  sort_order      integer not null,
  title_en        text not null,
  title_ar        text not null,
  description_en  text not null default '',
  description_ar  text not null default ''
);

create table if not exists public.practice_exercises (
  id                    integer generated by default as identity primary key,
  key                   text not null unique,
  type                  text not null check (type in ('Coding','Debugging','Scenario','CodeReview')),
  topic_id              integer not null references public.topics (id) on delete restrict,
  difficulty            text not null check (difficulty in ('Beginner','Intermediate','Advanced')),
  estimated_minutes     integer not null,
  title_en              text not null,
  title_ar              text not null,
  problem_en            text not null default '',
  problem_ar            text not null default '',
  code                  text,
  code_language         text,
  expected_outcome_en   text not null default '',
  expected_outcome_ar   text not null default '',
  hints_en              text not null default '',
  hints_ar              text not null default '',
  solution_en           text not null default '',
  solution_ar           text not null default '',
  solution_code         text
);
create index if not exists practice_exercises_type_topic_idx on public.practice_exercises (type, topic_id);

create table if not exists public.interview_questions (
  id              integer generated by default as identity primary key,
  key             text not null unique,
  category        text not null check (category in ('CSharp','DotNet','AspNetCore','EfCore','SqlServer','TypeScript','Angular','RestApi','Testing','Git','FullStackDesign')),
  topic_id        integer not null references public.topics (id) on delete restrict,
  difficulty      text not null check (difficulty in ('Beginner','Intermediate','Advanced')),
  question_en     text not null,
  question_ar     text not null,
  answer_en       text not null default '',
  answer_ar       text not null default '',
  example_code    text,
  follow_up_en    text,
  follow_up_ar    text
);
create index if not exists interview_questions_category_topic_idx on public.interview_questions (category, topic_id);

-- ---------- User data ----------

create table if not exists public.topic_progress (
  user_id       uuid not null default auth.uid() references auth.users (id) on delete cascade,
  topic_id      integer not null references public.topics (id) on delete cascade,
  status        text not null default 'NotStarted' check (status in ('NotStarted','InProgress','Completed','Skipped')),
  knowledge     text not null default 'Unassessed' check (knowledge in ('Unassessed','AlreadyKnow','NeedReview','NeedToLearn')),
  confidence    integer check (confidence between 0 and 5),
  started_at    timestamptz,
  completed_at  timestamptz,
  updated_at    timestamptz not null default now(),
  primary key (user_id, topic_id)
);

create table if not exists public.review_schedules (
  user_id          uuid not null default auth.uid() references auth.users (id) on delete cascade,
  topic_id         integer not null references public.topics (id) on delete cascade,
  interval_days    integer not null,
  next_review_on   date not null,
  last_reviewed_on date,
  review_count     integer not null default 0,
  created_at       timestamptz not null default now(),
  primary key (user_id, topic_id)
);
create index if not exists review_schedules_next_idx on public.review_schedules (user_id, next_review_on);

create table if not exists public.study_sessions (
  id              integer generated by default as identity primary key,
  user_id         uuid not null default auth.uid() references auth.users (id) on delete cascade,
  topic_id        integer references public.topics (id) on delete set null,
  project_task_id integer references public.project_tasks (id) on delete set null,
  planned_minutes integer check (planned_minutes is null or (planned_minutes > 0 and planned_minutes <= 1440)),
  actual_minutes  integer not null check (actual_minutes > 0 and actual_minutes <= 1440),
  session_date    date not null,
  note            text check (char_length(note) <= 1000),
  created_at      timestamptz not null default now()
);
create index if not exists study_sessions_user_date_idx on public.study_sessions (user_id, session_date);

create table if not exists public.notes (
  id                       integer generated by default as identity primary key,
  user_id                  uuid not null default auth.uid() references auth.users (id) on delete cascade,
  title                    text not null check (char_length(title) <= 200),
  content                  text not null default '' check (char_length(content) <= 20000),
  -- A note can be attached to at most one item.
  topic_id                 integer references public.topics (id) on delete set null,
  project_id               integer references public.projects (id) on delete set null,
  project_task_id          integer references public.project_tasks (id) on delete set null,
  interview_question_id    integer references public.interview_questions (id) on delete set null,
  created_at               timestamptz not null default now(),
  updated_at               timestamptz not null default now(),
  constraint notes_single_link check (
    (case when topic_id is null then 0 else 1 end)
  + (case when project_id is null then 0 else 1 end)
  + (case when project_task_id is null then 0 else 1 end)
  + (case when interview_question_id is null then 0 else 1 end) <= 1)
);
create index if not exists notes_user_updated_idx on public.notes (user_id, updated_at desc);

create table if not exists public.project_repositories (
  user_id         uuid not null default auth.uid() references auth.users (id) on delete cascade,
  project_id      integer not null references public.projects (id) on delete cascade,
  repository_url  text check (char_length(repository_url) <= 1000),
  updated_at      timestamptz not null default now(),
  primary key (user_id, project_id)
);

create table if not exists public.project_task_progress (
  user_id         uuid not null default auth.uid() references auth.users (id) on delete cascade,
  project_task_id integer not null references public.project_tasks (id) on delete cascade,
  status          text not null default 'NotStarted' check (status in ('NotStarted','InProgress','Completed','Blocked')),
  blocked_reason  text check (char_length(blocked_reason) <= 500),
  started_at      timestamptz,
  completed_at    timestamptz,
  updated_at      timestamptz not null default now(),
  primary key (user_id, project_task_id)
);

create table if not exists public.portfolio_checks (
  user_id           uuid not null default auth.uid() references auth.users (id) on delete cascade,
  project_id        integer not null references public.projects (id) on delete cascade,
  checklist_item_id integer not null references public.portfolio_checklist_items (id) on delete cascade,
  is_done           boolean not null default false,
  updated_at        timestamptz not null default now(),
  primary key (user_id, project_id, checklist_item_id)
);

create table if not exists public.practice_progress (
  user_id           uuid not null default auth.uid() references auth.users (id) on delete cascade,
  exercise_id       integer not null references public.practice_exercises (id) on delete cascade,
  status            text not null default 'NotStarted' check (status in ('NotStarted','Attempted','Completed')),
  user_answer       text check (char_length(user_answer) <= 10000),
  hints_revealed    integer not null default 0,
  solution_revealed boolean not null default false,
  completed_at      timestamptz,
  updated_at        timestamptz not null default now(),
  primary key (user_id, exercise_id)
);

create table if not exists public.interview_progress (
  user_id           uuid not null default auth.uid() references auth.users (id) on delete cascade,
  question_id       integer not null references public.interview_questions (id) on delete cascade,
  rating            text not null check (rating in ('NeedReview','Partial','Confident')),
  times_practiced   integer not null default 0,
  last_practiced_at timestamptz not null default now(),
  primary key (user_id, question_id)
);

-- One preferences row per user (replaces the single-row Id = 1 table).
create table if not exists public.learning_preferences (
  user_id                     uuid primary key default auth.uid() references auth.users (id) on delete cascade,
  daily_goal_minutes          integer not null default 60 check (daily_goal_minutes between 10 and 600),
  allow_skipping_prerequisites boolean not null default false,
  focus_skill                 text check (focus_skill in ('CSharp','AspNetCore','EfCore','SqlServer','TypeScript','Angular','FullStack','Testing','Git','Professional')),
  week_starts_on              text not null default 'Monday' check (week_starts_on in ('Sunday','Monday','Tuesday','Wednesday','Thursday','Friday','Saturday')),
  updated_at                  timestamptz not null default now()
);

